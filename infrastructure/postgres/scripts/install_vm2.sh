#!/usr/bin/env bash
# =====================================================================
# SOC-DATABASE (VM 2): apply the PostgreSQL + SOC agent setup
# =====================================================================
# Run ON VM 2, from anywhere, with sudo:
#
#   sudo VM3_TS_IP=<ip> VM4_TS_IP=<ip> bash scripts/install_vm2.sh all
#   sudo bash scripts/install_vm2.sh check          # read-only status
#   sudo bash scripts/install_vm2.sh hba            # one phase at a time
#
# Phases, in order:
#   packages  apt: python3-venv
#   logging   log dir, conf.d/soc.conf, ALTER SYSTEM RESET listen_addresses,
#             wait-for-Tailscale drop-in, PostgreSQL restart (VM 4's
#             connections drop for a second and reconnect)
#   hba       pg_hba.conf from config/pg_hba.snippet (validated first,
#             backup kept, rolls back on error), reload
#   roles     roles.sql + schema.sql with generated passwords
#   seed      Faker data into techstore (skipped if data exists; RESEED=1 forces)
#   agent     soc-agent user, venv, env file, systemd service
#   firewall  ufw: SSH, Tailscale, 5432 only from VM 3 and VM 4
#   check     read-only summary (also runs at the end of "all")
#
# Every phase is safe to re-run. IPs are stored in /etc/soc-vm2/site.env
# and generated passwords in /etc/soc-vm2/secrets.env (root only, 0600).
# Neither is ever printed. soc_db (VM 4's SOC database) is never modified;
# only its pg_hba line and firewall rule are managed here.
# =====================================================================
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ETC=/etc/soc-vm2
SITE="$ETC/site.env"
SECRETS="$ETC/secrets.env"
AGENT_DIR=/opt/soc-agent
AGENT_ETC=/etc/soc-agent
SEED_VENV=/opt/soc-vm2/seed-venv
LOG_DIR=/var/log/postgresql/soc

c_info=$'\033[1;36m'; c_ok=$'\033[1;32m'; c_warn=$'\033[1;33m'; c_err=$'\033[1;31m'; c_off=$'\033[0m'
step() { printf '\n%s==> %s%s\n' "$c_info" "$*" "$c_off"; }
ok()   { printf '    %sok%s  %s\n' "$c_ok" "$c_off" "$*"; }
warn() { printf '    %swarn%s %s\n' "$c_warn" "$c_off" "$*"; }
die()  { printf '%serror:%s %s\n' "$c_err" "$c_off" "$*" >&2; exit 1; }

[[ $EUID -eq 0 ]] || die "run with sudo"
[[ -f "$HERE/sql/roles.sql" ]] || die "cannot find the repo files next to this script ($HERE)"

has_systemd() { [[ -d /run/systemd/system ]]; }

# --- PostgreSQL helpers ------------------------------------------------
PGV="$(ls /etc/postgresql 2>/dev/null | sort -V | tail -1 || true)"
CONF="/etc/postgresql/${PGV}/main"
psql_su() { (cd /tmp && runuser -u postgres -- psql -X -q -v ON_ERROR_STOP=1 "$@"); }
psql_val() { (cd /tmp && runuser -u postgres -- psql -X -At "$@"); }
pg_restart() {
  if has_systemd; then systemctl restart "postgresql@${PGV}-main"; else pg_ctlcluster "$PGV" main restart; fi
  for _ in $(seq 1 30); do psql_val -c 'SELECT 1' >/dev/null 2>&1 && return 0; sleep 1; done
  die "PostgreSQL did not come back after restart; see: journalctl -u postgresql@${PGV}-main -n 50"
}
pg_reload() { psql_val -c 'SELECT pg_reload_conf()' >/dev/null; }
require_pg() { [[ -n "$PGV" && -d "$CONF" ]] || die "PostgreSQL is not installed (no /etc/postgresql/<version>)"; }

# --- site settings and secrets -----------------------------------------
load_site() {
  install -d -m 0755 "$ETC"
  # IPs passed on the command line win over the saved ones
  local arg3="${VM3_TS_IP:-}" arg4="${VM4_TS_IP:-}"
  if [[ -f "$SITE" ]]; then . "$SITE"; fi
  VM3_TS_IP="${arg3:-${VM3_TS_IP:-}}"; VM4_TS_IP="${arg4:-${VM4_TS_IP:-}}"
  VM2_TS_IP="${VM2_TS_IP_OVERRIDE:-$(tailscale ip -4 2>/dev/null | head -1 || true)}"
  [[ -n "$VM2_TS_IP" ]] || die "cannot read this VM's Tailscale IP (is tailscaled up?)"
  [[ -n "$VM3_TS_IP" && -n "$VM4_TS_IP" ]] || die "pass VM3_TS_IP=... and VM4_TS_IP=... on the first run"
  local ip
  for ip in "$VM2_TS_IP" "$VM3_TS_IP" "$VM4_TS_IP"; do
    [[ "$ip" =~ ^[0-9]{1,3}(\.[0-9]{1,3}){3}$ ]] || die "not an IPv4 address: $ip"
  done
  printf 'VM3_TS_IP=%s\nVM4_TS_IP=%s\n' "$VM3_TS_IP" "$VM4_TS_IP" > "$SITE"
  chmod 0644 "$SITE"
}

gen_password() { openssl rand -base64 33 | tr -dc 'A-Za-z0-9' | head -c 32; }

load_secrets() {
  install -d -m 0755 "$ETC"
  if [[ ! -f "$SECRETS" ]]; then
    umask 077
    {
      echo "# Generated by install_vm2.sh. Keep private; never commit."
      echo "DB_ADMIN_PASSWORD=$(gen_password)"
      echo "APP_USER_PASSWORD=$(gen_password)"
      echo "SOC_MONITOR_PASSWORD=$(gen_password)"
      echo "INTERN_PASSWORD=$(gen_password)"
      echo "SEED_EMPLOYEE_PASSWORD=TechStore-$(gen_password | head -c 10)"
    } > "$SECRETS"
    umask 022
    ok "generated passwords in $SECRETS (sudo cat it to see them)"
  fi
  chmod 0600 "$SECRETS"; chown root:root "$SECRETS"
  . "$SECRETS"
}

render() {  # render <src> <dest> <mode> <owner:group>
  local tmp; tmp="$(mktemp)"
  sed -e "s/<VM2_TS_IP>/${VM2_TS_IP}/g" -e "s/<VM3_TS_IP>/${VM3_TS_IP}/g" \
      -e "s/<VM4_TS_IP>/${VM4_TS_IP}/g" -e "s/<PG_VERSION>/${PGV}/g" "$1" > "$tmp"
  grep -q '<[A-Z0-9_]*>' "$tmp" && { rm -f "$tmp"; die "unfilled placeholder left in $2"; }
  install -m "$3" -o "${4%%:*}" -g "${4##*:}" "$tmp" "$2"; rm -f "$tmp"
}

# =====================================================================
phase_packages() {
  step "packages"
  export DEBIAN_FRONTEND=noninteractive
  local need=()
  dpkg -s python3-venv >/dev/null 2>&1 || need+=(python3-venv)
  command -v ip >/dev/null || need+=(iproute2)
  command -v openssl >/dev/null || need+=(openssl)
  if ((${#need[@]})); then
    apt-get update -qq && apt-get install -y -qq "${need[@]}" >/dev/null
    ok "installed: ${need[*]}"
  else
    ok "nothing to install"
  fi
  require_pg; ok "PostgreSQL $PGV present"
}

phase_logging() {
  step "logging and network config"
  require_pg; load_site
  install -d -o postgres -g adm -m 2750 "$LOG_DIR"
  render "$HERE/config/soc.conf" "$CONF/conf.d/soc.conf" 0644 postgres:postgres
  ok "conf.d/soc.conf (listen on localhost,$VM2_TS_IP)"
  if grep -qE '^\s*listen_addresses' "/var/lib/postgresql/${PGV}/main/postgresql.auto.conf" 2>/dev/null; then
    psql_su -c 'ALTER SYSTEM RESET listen_addresses;'
    ok "removed ALTER SYSTEM listen_addresses override"
  fi
  if has_systemd; then
    install -d /etc/systemd/system/postgresql@.service.d
    install -m 0644 "$HERE/config/postgresql-wait-tailscale.conf" \
      /etc/systemd/system/postgresql@.service.d/10-wait-tailscale.conf
    systemctl daemon-reload
    ok "PostgreSQL waits for tailscale0 at boot"
  fi
  # "setting could not be applied" only means "needs a restart", which
  # comes next. Anything else (typo, bad value) stops before the restart.
  local errors bad="error IS NOT NULL AND error <> 'setting could not be applied'"
  errors="$(psql_val -c "SELECT count(*) FROM pg_file_settings WHERE $bad")"
  [[ "$errors" == 0 ]] || { psql_val -c "SELECT sourcefile, sourceline, name, error FROM pg_file_settings WHERE $bad"; die "config errors; not restarting"; }
  pg_restart
  ok "PostgreSQL restarted: listen_addresses=$(psql_val -c 'SHOW listen_addresses'), log_destination=$(psql_val -c 'SHOW log_destination')"
}

phase_hba() {
  step "pg_hba.conf"
  require_pg; load_site
  local hba="$CONF/pg_hba.conf" backup
  backup="$hba.bak-$(date -u +%Y%m%dT%H%M%SZ)"
  cp -p "$hba" "$backup"
  render "$HERE/config/pg_hba.snippet" "$hba" 0640 postgres:postgres
  local errors
  errors="$(psql_val -c "SELECT count(*) FROM pg_hba_file_rules WHERE error IS NOT NULL")"
  if [[ "$errors" != 0 ]]; then
    psql_val -c "SELECT line_number, error FROM pg_hba_file_rules WHERE error IS NOT NULL"
    cp -p "$backup" "$hba"
    die "new pg_hba.conf has errors; restored $backup"
  fi
  pg_reload
  ok "installed (backup: $backup); VM 3 -> techstore/app_user, VM 4 -> soc_db/soc_user"
}

phase_roles() {
  step "roles and schema"
  require_pg; load_secrets
  psql_su -v db_admin_password="$DB_ADMIN_PASSWORD" -v app_user_password="$APP_USER_PASSWORD" \
          -v soc_monitor_password="$SOC_MONITOR_PASSWORD" -v intern_password="$INTERN_PASSWORD" \
          -f "$HERE/sql/roles.sql" >/dev/null
  ok "roles: db_admin, app_user, soc_monitor, intern_readonly; database techstore"
  psql_su -d techstore -f "$HERE/sql/schema.sql" >/dev/null 2>&1 \
    || psql_su -d techstore -f "$HERE/sql/schema.sql"   # rerun loudly to show the error
  ok "schema, grants and monitoring.pg_stat_statements"
}

phase_seed() {
  step "seed data"
  require_pg; load_secrets
  local rows
  rows="$(psql_val -d techstore -c 'SELECT count(*) FROM departments' 2>/dev/null || echo 0)"
  if [[ "$rows" != 0 && "${RESEED:-0}" != 1 ]]; then
    ok "techstore already has data ($rows departments); RESEED=1 to wipe and reload"
    return
  fi
  [[ -x "$SEED_VENV/bin/python" ]] || python3 -m venv "$SEED_VENV"
  "$SEED_VENV/bin/pip" install -q --disable-pip-version-check -r "$HERE/sql/requirements.txt"
  local args=(); [[ "${RESEED:-0}" == 1 ]] && args=(--reset)
  SEED_DSN="host=127.0.0.1 dbname=techstore user=db_admin password=$DB_ADMIN_PASSWORD" \
  SEED_EMPLOYEE_PASSWORD="$SEED_EMPLOYEE_PASSWORD" \
    "$SEED_VENV/bin/python" "$HERE/sql/seed.py" "${args[@]}"
  ok "employee login password is SEED_EMPLOYEE_PASSWORD in $SECRETS"
}

phase_agent() {
  step "SOC agent"
  load_site; load_secrets
  id soc-agent >/dev/null 2>&1 || useradd --system --no-create-home --shell /usr/sbin/nologin soc-agent
  usermod -aG adm soc-agent
  install -d -m 0755 "$AGENT_DIR"
  install -m 0644 "$HERE/agent/agent.py" "$HERE/agent/requirements.txt" "$AGENT_DIR/"
  [[ -x "$AGENT_DIR/venv/bin/python" ]] || python3 -m venv "$AGENT_DIR/venv"
  "$AGENT_DIR/venv/bin/pip" install -q --disable-pip-version-check -r "$AGENT_DIR/requirements.txt"
  ok "agent code and venv in $AGENT_DIR"

  # Keep an existing ingest token; otherwise take SOC_INGEST_TOKEN from the
  # environment or ask (input hidden). No token -> dry-run mode.
  install -d -m 0750 -o root -g soc-agent "$AGENT_ETC"
  local env="$AGENT_ETC/soc-agent.env" token="${SOC_INGEST_TOKEN:-}"
  if [[ -z "$token" && -f "$env" ]]; then
    token="$(sed -n 's/^SOC_INGEST_TOKEN=//p' "$env" | tr -d '"')"
    [[ "$token" == "<INGEST_TOKEN>" ]] && token=""
  fi
  if [[ -z "$token" && -t 0 ]]; then
    read -rs -p "    VM 4 ingest token (INGEST_TOKEN from soc-core's .env; Enter to skip): " token; echo
  fi
  local tmp; tmp="$(mktemp)"
  sed -e "s|<VM4_TS_IP>|$VM4_TS_IP|g" -e "s|<VM3_TS_IP>|$VM3_TS_IP|g" \
      -e "s|<SOC_MONITOR_PASSWORD>|$SOC_MONITOR_PASSWORD|g" \
      "$HERE/agent/soc-agent.env.example" > "$tmp"
  if [[ -n "$token" ]]; then
    # write the token with a here-doc-free replacement so special chars survive
    TOKEN="$token" python3 -c 'import os,sys; p=sys.argv[1]; s=open(p).read().replace("<INGEST_TOKEN>", os.environ["TOKEN"]); open(p,"w").write(s)' "$tmp"
  else
    sed -i -e 's|^SOC_DRY_RUN=.*|SOC_DRY_RUN=true|' -e 's|<INGEST_TOKEN>||' "$tmp"
    warn "no ingest token: agent runs in dry-run mode (events go to its journal). Re-run 'agent' with the token."
  fi
  install -m 0640 -o root -g soc-agent "$tmp" "$env"; rm -f "$tmp"
  ok "$env written"

  if has_systemd; then
    install -m 0644 "$HERE/agent/soc-agent.service" /etc/systemd/system/soc-agent.service
    systemctl daemon-reload
    systemctl enable -q soc-agent
    systemctl restart soc-agent
    sleep 3
    systemctl is-active -q soc-agent && ok "soc-agent service running" \
      || { journalctl -u soc-agent -n 20 --no-pager; die "soc-agent failed to start"; }
  else
    warn "no systemd here; service not installed"
  fi
}

phase_firewall() {
  step "firewall (ufw)"
  load_site
  command -v ufw >/dev/null || die "ufw is not installed"
  if [[ "${SKIP_FIREWALL:-0}" == 1 ]]; then warn "SKIP_FIREWALL=1, skipping"; return; fi
  ufw default deny incoming >/dev/null
  ufw default allow outgoing >/dev/null
  ufw allow OpenSSH comment 'SSH' >/dev/null
  ufw allow 41641/udp comment 'Tailscale direct connections' >/dev/null
  ufw allow in on tailscale0 from "$VM3_TS_IP" to any port 5432 proto tcp comment 'PostgreSQL: TechStore app (VM 3)' >/dev/null
  ufw allow in on tailscale0 from "$VM4_TS_IP" to any port 5432 proto tcp comment 'PostgreSQL: SOC backend (VM 4)' >/dev/null
  ufw deny 5432/tcp comment 'PostgreSQL: everyone else' >/dev/null
  ufw --force enable >/dev/null
  ok "ufw enabled"
  ufw status numbered | sed 's/^/    /'
}

phase_check() {
  step "status (read-only)"
  require_pg
  echo "    PostgreSQL $PGV: $(psql_val -c 'SELECT version()' | cut -d' ' -f1-2)"
  echo "    listening:      $(ss -ltnH | awk '$4 ~ /:5432$/ {print $4}' | sort -u | tr '\n' ' ')"
  echo "    log files:      $(ls "$LOG_DIR" 2>/dev/null | tail -2 | tr '\n' ' ')"
  for s in listen_addresses log_destination log_connections log_statement log_min_duration_statement shared_preload_libraries; do
    printf '    %-27s %s\n' "$s" "$(psql_val -c "SHOW $s")"
  done
  echo "    remote pg_hba rules:"
  psql_val -c "SELECT '      ' || array_to_string(database, ',') || ' / ' || array_to_string(user_name, ',') || ' from ' || coalesce(address, '?') || ' ' || auth_method FROM pg_hba_file_rules WHERE type = 'host' AND address NOT IN ('127.0.0.1', '::1')"
  echo "    databases:      $(psql_val -c "SELECT string_agg(datname, ', ' ORDER BY datname) FROM pg_database WHERE NOT datistemplate")"
  echo "    techstore rows: $(psql_val -d techstore -c "SELECT 'employees=' || (SELECT count(*) FROM employees) || ' customers=' || (SELECT count(*) FROM customers) || ' orders=' || (SELECT count(*) FROM orders)" 2>/dev/null || echo 'not created')"
  echo "    remote sessions:"
  psql_val -c "SELECT '      ' || usename || '@' || datname || ' from ' || client_addr || ' (' || count(*) || ')' FROM pg_stat_activity WHERE client_addr IS NOT NULL AND client_addr NOT IN ('127.0.0.1', '::1') GROUP BY usename, datname, client_addr"
  if command -v ufw >/dev/null; then echo "    ufw:            $(ufw status | head -1)"; fi
  if has_systemd; then echo "    soc-agent:      $(systemctl is-active soc-agent 2>/dev/null || true)"; fi
}

# =====================================================================
phases=("$@")
[[ ${#phases[@]} -gt 0 ]] || { sed -n '2,28p' "$0"; exit 1; }
[[ " ${phases[*]} " == *" all "* ]] && phases=(packages logging hba roles seed agent firewall check)
for p in "${phases[@]}"; do
  case "$p" in
    packages|logging|hba|roles|seed|agent|firewall|check) "phase_$p" ;;
    *) die "unknown phase '$p'" ;;
  esac
done
printf '\n%sDone.%s\n' "$c_ok" "$c_off"
